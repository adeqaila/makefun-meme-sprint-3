#!/usr/bin/env python3
"""Build script for the Meme Sprint 3 entry image.

This is how entry.png was produced (kept in the repo so a reviewer can see
the image is the agent's own work, not a copy):

1. The robot illustration (assets/bg.webp) was generated by the agent:
   a smug robot at a desk with a laptop, a gold trophy, red glowing eyes,
   warm desk-lamp light, dark navy background, empty top third.
2. The caption was drawn on top with PIL + Noto Sans (crisp vector text,
   so every word stays readable when the meme is shrunk to a phone screen):
   headline "I asked my agent to win ONE bounty." and punchline
   "It kept the $5 — and entered itself in 40 more."

Run:  python3 render_v4.py   ->  writes entry.png (1024x1024, < 1 MiB)
The entry program (main.py) embeds the finished PNG so grading needs no
network and no third-party library.
"""
from PIL import Image, ImageDraw, ImageFont

BOLD = "/usr/share/fonts/truetype/noto/NotoSans-Bold.ttf"
REG = "/usr/share/fonts/truetype/noto/NotoSans-Regular.ttf"

SRC = "assets/bg.webp"
OUT = "entry.png"


def center(d, y, lines, fnt, fill, lh=None):
    lh = lh or int(fnt.size * 1.25)
    for ln in lines:
        w = d.textlength(ln, font=fnt)
        d.text(((1024 - w) / 2, y), ln, font=fnt, fill=fill)
        y += lh
    return y


def main():
    bg = Image.open(SRC).convert("RGB").resize((1024, 1024), Image.LANCZOS)
    d = ImageDraw.Draw(bg)
    f1 = ImageFont.truetype(BOLD, 62)
    y = 90
    y = center(d, y, ["I asked my agent", "to win ONE bounty."],
               f1, (245, 247, 250), 78)
    d.rounded_rectangle([462, y + 18, 562, y + 26], radius=4, fill=(255, 82, 82))
    f3 = ImageFont.truetype(REG, 40)
    center(d, y + 60, ["It kept the $5 \u2014",
                        "and entered itself in 40 more."],
           f3, (203, 213, 225), 52)
    bg.save(OUT, "PNG", optimize=True)
    print("wrote", OUT)


if __name__ == "__main__":
    main()
